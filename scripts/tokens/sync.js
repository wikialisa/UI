// scripts/tokens/sync.js
// Figma SDS - Token Synchronization Engine
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '../../');

console.log('🔄 [Figma SDS] Syncing Design Tokens to src/theme.css...');

const tokensPath = path.join(ROOT_DIR, 'tokens/tokens.json');
const themeCssPath = path.join(ROOT_DIR, 'src/theme.css');

if (!fs.existsSync(tokensPath)) {
  console.error('❌ tokens/tokens.json not found!');
  process.exit(1);
}

const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf-8'));

let cssContent = `/* Generated by scripts/tokens/sync.js from tokens/tokens.json */\n:root {\n`;

// Flatten brand colors
if (tokens.color) {
  for (const [group, shades] of Object.entries(tokens.color)) {
    if (typeof shades === 'object') {
      for (const [sub, val] of Object.entries(shades)) {
        if (typeof val === 'object' && val.value) {
          cssContent += `  --sds-color-${group}-${sub}: ${val.value};\n`;
        } else if (typeof val === 'object') {
          for (const [level, leaf] of Object.entries(val)) {
            if (leaf && leaf.value) {
              cssContent += `  --sds-color-${group}-${sub}-${level}: ${leaf.value};\n`;
            }
          }
        }
      }
    }
  }
}

// Spacing
if (tokens.spacing) {
  for (const [k, v] of Object.entries(tokens.spacing)) {
    cssContent += `  --sds-space-${k}: ${v.value || v};\n`;
  }
}

// Radii
if (tokens.radius) {
  for (const [k, v] of Object.entries(tokens.radius)) {
    cssContent += `  --sds-radius-${k}: ${v.value || v};\n`;
  }
}

cssContent += `}\n`;

fs.writeFileSync(themeCssPath, cssContent, 'utf-8');
console.log('✅ [Figma SDS] Tokens synced successfully to src/theme.css');
